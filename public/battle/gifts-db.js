//  Gift Picker UI 
const GiftPicker = {
    selected: { boys: new Set(), girls: new Set() },

    render(containerId) {
        const container = document.getElementById(containerId);
        if (!container) return;

        let html = `
        <div class="gift-picker-header">
            <div class="gift-picker-tabs">
                <button class="gpick-tab active" onclick="GiftPicker.filterRarity('all',this)"></button>
                <button class="gpick-tab" onclick="GiftPicker.filterRarity('common',this)"></button>
                <button class="gpick-tab" onclick="GiftPicker.filterRarity('uncommon',this)"></button>
                <button class="gpick-tab" onclick="GiftPicker.filterRarity('rare',this)"></button>
                <button class="gpick-tab" onclick="GiftPicker.filterRarity('epic',this)"></button>
            </div>
        </div>
        <div class="gift-grid" id="gift-grid">`;

        TIKTOK_GIFTS.forEach(g => {
            html += `
            <div class="gift-card-v2" id="gc-${g.id}" data-id="${g.id}" data-rarity="${g.rarity}">
                <div class="gc-team-indicators">
                    <div class="gc-team-btn gc-boy-btn" onclick="GiftPicker.assign('${g.id}','boys')" title=""></div>
                    <div class="gc-team-btn gc-girl-btn" onclick="GiftPicker.assign('${g.id}','girls')" title=""></div>
                </div>
                <div class="gc-image-area">
                    <img src="${g.img}" class="gc-real-img" loading="lazy" onerror="this.onerror=null; this.src='https://raw.githubusercontent.com/microsoft/fluentui-emoji/main/assets/Package/3D/package_3d.png';">
                </div>
                <div class="gc-info">
                    <div class="gc-name">${g.nameAr}</div>
                    <div class="gc-price"> ${g.diamonds}</div>
                </div>
                <div class="gc-sel-marker marker-boys" id="bs-${g.id}"></div>
                <div class="gc-sel-marker marker-girls" id="gs-${g.id}"></div>
            </div>`;
        });

        html += `</div>
        <div class="gift-picker-footer">
            <div class="team-sel-preview boys-preview">
                <span class="p-label">:</span>
                <div id="boys-sel-list" class="p-list"> </div>
            </div>
            <div class="team-sel-preview girls-preview">
                <span class="p-label">:</span>
                <div id="girls-sel-list" class="p-list"> </div>
            </div>
        </div>`;

        container.innerHTML = html;
        this._updateSummary();
    },

    assign(giftId, team) {
        const opTeam = team === 'boys' ? 'girls' : 'boys';
        const card = document.getElementById('gc-' + giftId);
        if (!card) return;
        
        if (this.selected[team].has(giftId)) {
            this.selected[team].delete(giftId);
            card.classList.remove('active-' + team);
            document.getElementById((team === 'boys' ? 'bs' : 'gs') + '-' + giftId).style.display = 'none';
        } else {
            this.selected[opTeam].delete(giftId);
            card.classList.remove('active-' + opTeam);
            const opMarker = document.getElementById((opTeam === 'boys' ? 'bs' : 'gs') + '-' + giftId);
            if (opMarker) opMarker.style.display = 'none';
            
            this.selected[team].add(giftId);
            card.classList.add('active-' + team);
            document.getElementById((team === 'boys' ? 'bs' : 'gs') + '-' + giftId).style.display = 'flex';
        }
        this._updateSummary();
    },

    filterRarity(rarity, btn) {
        document.querySelectorAll('.gpick-tab').forEach(t => t.classList.remove('active'));
        btn.classList.add('active');
        document.querySelectorAll('.gift-card-v2').forEach(card => {
            card.style.display = (rarity === 'all' || card.dataset.rarity === rarity) ? '' : 'none';
        });
    },

    _updateSummary() {
        const fmt = team => {
            const items = [...this.selected[team]].map(id => TIKTOK_GIFTS.find(x => x.id === id)?.emoji || id);
            return items.length ? items.join(' ') : ' ';
        };
        const boysList = document.getElementById('boys-sel-list');
        const girlsList = document.getElementById('girls-sel-list');
        if (boysList) boysList.textContent = fmt('boys');
        if (girlsList) girlsList.textContent = fmt('girls');
    },

    getConfig(team) {
        return [...this.selected[team]].map(id => {
            const g = TIKTOK_GIFTS.find(x => x.id === id);
            return g ? { name: g.nameEn, pts: g.pts, emoji: g.emoji } : null;
        }).filter(Boolean);
    },

    // مطابقة اسم الهدية بدقة عالية لمنع تداخل الهدايا (مثل الوردة 1 عملة مع وردة 10 عملات)
    matchGift(data) {
        if (!data) return null;
        const giftNameRaw = typeof data === 'string' ? data : data.giftName;
        const diamonds = (typeof data === 'object' && data.diamondCount !== undefined) ? data.diamondCount : null;
        if (!giftNameRaw) return null;

        const lower = giftNameRaw.toLowerCase().trim().replace(/\s+/g, '_');

        for (const g of TIKTOK_GIFTS) {
            // تحقق صارم من عدد العملات لتجنب الخلط تماماً
            if (diamonds !== null && g.diamonds !== undefined && diamonds !== g.diamonds) {
                continue;
            }

            const enClean = g.nameEn.toLowerCase().trim().replace(/\s+/g, '_');
            const arClean = (g.nameAr || '').trim().replace(/\s+/g, '_');

            // تطابق تام
            if (lower === enClean || lower === arClean || lower === g.id.toLowerCase()) {
                if (this.selected.boys.has(g.id))  return { team: 'boys',  pts: g.pts, gift: g };
                if (this.selected.girls.has(g.id)) return { team: 'girls', pts: g.pts, gift: g };
            }
            
            // تطابق جزئي آمن (لن يتم إلا إذا كانت العملات متطابقة تماماً)
            if (lower.includes(enClean) || (g.id.length > 2 && lower.includes(g.id))) {
                if (this.selected.boys.has(g.id))  return { team: 'boys',  pts: g.pts, gift: g };
                if (this.selected.girls.has(g.id)) return { team: 'girls', pts: g.pts, gift: g };
            }
        }
        return null;
    }
};
